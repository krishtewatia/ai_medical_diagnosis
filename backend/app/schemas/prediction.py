from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, field_validator


class PredictionRequest(BaseModel):
    """
    Standard incoming request for tabular disease predictions.
    Generic across all diseases; disease-specific input keys are validated
    dynamically by the disease configuration and predictor layers.
    """
    disease_id: str = Field(
        ...,
        min_length=1,
        max_length=50,
        description="Unique identifier for the target disease model (e.g. 'diabetes', 'heart_disease').",
        examples=["diabetes"]
    )
    inputs: Dict[str, Any] = Field(
        default_factory=dict,
        description="Dictionary containing disease-specific input features.",
        examples=[{"Glucose": 140, "BMI": 28.5, "Age": 45}]
    )

    @field_validator("disease_id")
    @classmethod
    def validate_disease_id(cls, v: str) -> str:
        v_stripped = v.strip().lower()
        if not v_stripped:
            raise ValueError("disease_id cannot be empty or whitespace.")
        return v_stripped


class PredictionResult(BaseModel):
    """
    Standard internal result object produced by ML Predictors (both Tabular and Image).
    Independent of HTTP, database schemas, and reporting concerns.
    """
    disease_id: str
    disease_display_name: str
    model_version: str
    model_type: str

    # Core Prediction Outputs
    prediction_label: str
    is_positive: bool
    probability: Optional[float] = Field(None, ge=0.0, le=1.0)
    decision_threshold: float = Field(default=0.50, ge=0.0, le=1.0)

    # Optional model-specific telemetry/metadata (e.g. inference time in ms, intermediate scores)
    metadata: Dict[str, Any] = Field(default_factory=dict)
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class PredictionResponse(BaseModel):
    """
    Standardized external API response returned for all disease screenings (tabular and image).
    Consistently structures ML classifications, probability/confidence scores, thresholds,
    telemetry, and explicit clinical safety boundaries.
    """
    disease_id: str = Field(..., description="Unique disease identifier (e.g. 'diabetes', 'heart_disease', 'pneumonia').")
    disease_display_name: str = Field(..., description="Human-readable display name for the disease.")
    
    # 1. Model Classification Output
    prediction_label: str = Field(..., description="Classification outcome label (e.g. 'High Risk of Diabetes', 'Lung Opacity Detected').")
    is_positive: bool = Field(..., description="Boolean flag indicating elevated risk or positive screening finding.")
    probability: Optional[float] = Field(
        None,
        ge=0.0,
        le=1.0,
        description="Calibrated probability or confidence score (0.0 to 1.0) when supported by the model."
    )
    decision_threshold: Optional[float] = Field(
        default=0.50,
        ge=0.0,
        le=1.0,
        description="Configured decision threshold used to classify positive outcome."
    )
    
    # 2. Model Telemetry & Lineage
    model_version: str = Field(..., description="Model version tag (e.g. 'v1').")
    model_type: str = Field(..., description="Model architecture/family (e.g. 'LogisticRegression', 'XGBoost', 'DenseNet121').")
    
    # 3. Medical Safety & Explanatory Context
    explanation: Optional[str] = Field(
        default=None,
        description="High-level narrative summary of the screening result for frontend presentation."
    )
    clinical_purpose: Optional[str] = Field(
        default="Screening/research prototype only, not a definitive medical diagnosis.",
        description="Intended clinical or screening purpose."
    )
    disclaimer: Optional[str] = Field(
        default=(
            "This result is generated by an AI screening prototype and does not represent a medical diagnosis. "
            "Always consult a qualified medical professional."
        ),
        description="Mandatory legal and medical disclaimer distinguishing ML screening from definitive medical diagnosis."
    )
    limitations: Optional[str] = Field(
        default="Not suitable as a primary or sole diagnostic decision instrument.",
        description="Known technical or clinical limitations of the model."
    )
    
    # 4. Telemetry & Execution Metadata
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Inference telemetry (e.g. latency_ms, feature count, input shape)."
    )
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp when prediction was generated."
    )

    @classmethod
    def from_result(
        cls,
        result: PredictionResult,
        explanation: Optional[str] = None,
        clinical_purpose: Optional[str] = None,
        disclaimer: Optional[str] = None,
        limitations: Optional[str] = None
    ) -> "PredictionResponse":
        """Factory helper creating a standardized API response directly from an internal PredictionResult."""
        default_explanation = f"Model evaluation resulted in '{result.prediction_label}' based on submitted clinical indicators."
        return cls(
            disease_id=result.disease_id,
            disease_display_name=result.disease_display_name,
            prediction_label=result.prediction_label,
            is_positive=result.is_positive,
            probability=result.probability,
            decision_threshold=result.decision_threshold,
            model_version=result.model_version,
            model_type=result.model_type,
            explanation=explanation or default_explanation,
            clinical_purpose=clinical_purpose or "Screening/research prototype only, not a definitive medical diagnosis.",
            disclaimer=disclaimer or (
                "This result is generated by an AI screening prototype and does not represent a medical diagnosis. "
                "Always consult a qualified medical professional."
            ),
            limitations=limitations or "Not suitable as a primary or sole diagnostic decision instrument.",
            metadata=result.metadata,
            timestamp=result.timestamp,
        )


class PredictionRequestPayload(BaseModel):
    """
    Internal container for raw prediction inputs before being dispatched to a predictor.
    Supports either tabular feature dictionary or raw image bytes.
    """
    disease_id: str
    tabular_inputs: Optional[Dict[str, Any]] = None
    image_bytes: Optional[bytes] = None
    image_content_type: Optional[str] = None
